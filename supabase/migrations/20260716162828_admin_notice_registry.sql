-- 管理画面から追加・編集・削除できる下書き台帳（現時点では管理者専用・ユーザーへの配信機能は未実装）
create table public.admin_notice_registry (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  body text not null default '',
  sort integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.admin_notice_registry enable row level security;

create policy "notice registry admin all" on public.admin_notice_registry
  for all to authenticated
  using (exists (select 1 from public.app_admins a where a.auth_id = auth.uid()))
  with check (exists (select 1 from public.app_admins a where a.auth_id = auth.uid()));

