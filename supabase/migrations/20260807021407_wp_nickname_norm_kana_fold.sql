-- ニックネームの仮名折り畳み（2026-08-07 たきと裁定「必要」）：
-- ひらがな⇄カタカナだけ違う名前（はなこ vs ハナコ vs ﾊﾅｺ）を同名として拒否する。
-- 「はなこ」と「ハナコ」が別人として並ぶ取り違えを防ぐ（#1052の「たき」2人事件の再発防止の仕上げ）。
-- 方式＝NFKC後にカタカナ(U+30A1..U+30F6)をひらがな(U+3041..U+3096)へtranslate（コード-96の平行移動。
-- 濁点・半濁点付き・小書き・ゔゕゖを含む86文字。長音「ー」は両仮名共通なのでそのまま）。
-- 半角カナはNFKCが先に全角カタカナへ畳むので、この1段で ﾊﾅｺ→ハナコ→はなこ が繋がる。
-- 既存データへの影響＝事前実測で新たな衝突ゼロ（既知の「たき」×2のみ・グランドファーザー不変）。
create or replace function public.wp_nickname_norm(p text)
returns text language sql immutable as $$
  select lower(
    regexp_replace(
      translate(
        regexp_replace(
          normalize(coalesce(p,''), NFKC),
          -- ZWSP/ZWNJ/ZWJ/LRM/RLM/WJ/BOM/SHY（NFKCが残す不可視文字）を全削除
          '[' || chr(8203) || chr(8204) || chr(8205) || chr(8206) || chr(8207) || chr(8288) || chr(65279) || chr(173) || ']', '', 'g'),
        'ァアィイゥウェエォオカガキギクグケゲコゴサザシジスズセゼソゾタダチヂッツヅテデトドナニヌネノハバパヒビピフブプヘベペホボポマミムメモャヤュユョヨラリルレロヮワヰヱヲンヴヵヶ',
        'ぁあぃいぅうぇえぉおかがきぎくぐけげこごさざしじすずせぜそぞただちぢっつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽまみむめもゃやゅゆょよらりるれろゎわゐゑをんゔゕゖ'),
      '(^\s+)|(\s+$)', '', 'g')
  )
$$;
